// כל האירועים בקבוצה נתונה
export function occasionsByGroup(groupId) {
  return READY_OCCASIONS.filter(o => o.group === groupId)
}

// מציאת אירוע לפי id
export function findOccasion(id) {
  return READY_OCCASIONS.find(o => o.id === id) || null
}

// הזרקת שם הנמען לטקסט. אם אין שם — מסיר את {שם} בעדינות (כולל פסיק/רווח אחריו).
export function fillName(text, name) {
  const n = (name || '').trim()
  if (!n) return (text || '').replace(/\{שם\}\s*,?\s*/g, '').replace(/\s{2,}/g, ' ').trim()
  return (text || '').replace(/\{שם\}/g, n)
}

// בחירת ברכה אקראית לאירוע (excludeIdx כדי לא לחזור על אותה ברכה ב"ברכה אחרת")
export function randomGreeting(occasionId, excludeIdx = -1) {
  const arr = READY_GREETINGS[occasionId] || []
  if (arr.length === 0) return { idx: -1, text: '' }
  if (arr.length === 1) return { idx: 0, text: arr[0] }
  let idx = excludeIdx
  while (idx === excludeIdx) idx = Math.floor(Math.random() * arr.length)
  return { idx, text: arr[idx] }
}

// כתובת רקע אקראי מהתיקייה של האירוע (1..bgCount)
export function randomBgUrl(occasion, excludeUrl = null) {
  if (!occasion || !occasion.bgCount) return null
  let url = excludeUrl
  for (let i = 0; i < 6 && (url === excludeUrl || !url); i++) {
    const n = 1 + Math.floor(Math.random() * occasion.bgCount)
    url = `/backgrounds/${encodeURIComponent(occasion.bgDir)}/${n}.png`
    if (occasion.bgCount === 1) break
  }
  return url
}
