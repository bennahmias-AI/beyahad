async function seed() {
  console.log('🌱 מתחיל הזרעה...')

  const sysUid = 'seed-system'

  let count = 0
  for (const r of RECIPES) {
    await addDoc(collection(db, 'communityPosts'), {
      kind: 'recipe',
      title: r.title,
      body: r.body,
      authorUid: sysUid,
      authorName: r.author,
      views: Math.floor(Math.random() * 80) + 12,   // 12–91 צפיות
      likes: [],
      createdAt: serverTimestamp(),
    })
    count++
    console.log(`  🍲 ${r.title}`)
  }

  for (const t of TIPS) {
    await addDoc(collection(db, 'communityPosts'), {
      kind: 'tip',
      title: t.title,
      body: t.body,
      authorUid: sysUid,
      authorName: t.author,
      views: Math.floor(Math.random() * 80) + 12,
      likes: [],
      createdAt: serverTimestamp(),
    })
    count++
    console.log(`  💡 ${t.title}`)
  }

  console.log(`\n✅ הוכנסו ${count} פריטים בהצלחה!`)
  process.exit(0)
}

seed().catch(err => {
  console.error('❌ שגיאה:', err)
  process.exit(1)
})
